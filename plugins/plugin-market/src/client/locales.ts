/**
 * Dictionary of the plugin market (sidebar entry + drawer panel), in this
 * plugin's own locale namespace.
 *
 * The namespace is declared by the client entry (`src/client.ts`, the
 * `declare module` merge into `LocaleNamespaceMap`); this module owns the keys.
 * One namespace per plugin, because a namespace has exactly one owner; keys
 * carry a `mkt.` prefix so a later page of this plugin never collides here.
 *
 * zh is the source of truth and stays byte-identical to the pre-i18n panel
 * copy; {@link MarketKey} is its key union, and the English dictionary is typed
 * with it, so a missing or extra key on either side is a compile error. The
 * same union constrains the panel's `t` seat (`PropsLocale`), so a key removed
 * from the dictionary cannot be rendered.
 *
 * Remarks on the zh values, all consequences of "the rendered text does not
 * change":
 *
 * - Multi-line JSX text collapses to one line with single spaces where the
 *   line breaks were; the dictionary carries the collapsed text, which is what
 *   the panel rendered before.
 * - Strings the pre-i18n code composed from fragments (a conditional note, a
 *   list joined by a separator, a clause list) stay separate keys, and each
 *   locale's fragment carries its own punctuation — a joiner hardcoded in code
 *   cannot serve both languages.
 * - Where a separator sat directly after a spinner, the leading space is part
 *   of the value (`' 安装中…'`) when the spinner is a conditional sibling with
 *   no text node of its own; where the pre-i18n JSX already carried that space
 *   as text (the loading lines), it stays in the JSX and the value has none.
 *   Either way the rendered text is unchanged.
 *
 * @module @dsh-app/plugin-market/client/locales
 */

