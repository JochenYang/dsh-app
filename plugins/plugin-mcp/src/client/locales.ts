/**
 * Dictionary of the MCP settings page, in this plugin's own locale namespace.
 *
 * The namespace is declared by the client entry (`src/client.ts`, the
 * `declare module` merge into `LocaleNamespaceMap`); this module owns the
 * keys. One namespace per plugin, because a namespace has exactly one owner.
 *
 * zh is the source of truth and stays byte-identical to the pre-i18n page
 * copy; {@link McpKey} is its key union, and the English dictionary is typed
 * with it, so a missing or extra key on either side is a compile error. The
 * same union constrains the page's `t` seat (`TranslateNS`), so a key removed
 * from the dictionary cannot be rendered.
 *
 * `{name}`-style placeholders are the upstream template syntax. Copy for the
 * HOST half's messages lives here too, under `mcp.host.*`: the host sends a
 * stable code plus the values its sentence interpolates (see `HostText` in
 * ../wire.ts) and this dictionary renders it, so the host never has to know
 * the UI's language.
 *
 * @module @dsh-app/plugin-mcp/client/locales
 */

