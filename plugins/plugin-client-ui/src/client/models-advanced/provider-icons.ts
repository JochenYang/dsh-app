/** The loader's package-asset resolver, present on the `require` a client
 *  bundle factory receives (see `ClientBundleRequire`). Declared once here, at
 *  the only call site that reads it: the TypeScript `require` type comes from
 *  the Node types the plugin's typecheck resolves, which carry no loader
 *  surface. */
declare global {
  namespace NodeJS {
    interface Require {
      /** Resolve `plugins/<package>/assets/<path>` to a loadable URL. */
      asset?: (reference: string) => string
    }
  }
}

/**
 * Resolve a packaged asset reference to the URL the page loads.
 *
 * The desktop shell forwards `dsh-app://app/plugins/…` to the kernel's package
 * asset route; a bundle materialized outside a loader (a unit test) gets the
 * document-relative path, which the same route answers.
 *
 * @param reference - `plugins/<package>/assets/<path>`.
 * @returns the loadable URL.
 */
function asset(reference: string): string {
  const resolved = typeof require === 'function' ? require.asset?.(reference) : undefined
  return typeof resolved === 'string' && resolved !== '' ? resolved : `/${reference}`
}

