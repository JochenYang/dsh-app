/**
 * Dictionary of the web search settings page, in this plugin's own locale
 * namespace.
 *
 * The namespace is declared by the client entry (`src/client.ts`, the
 * `declare module` merge into `LocaleNamespaceMap`); this module owns the
 * keys. One namespace per plugin, because a namespace has exactly one owner.
 *
 * zh is the source of truth and stays byte-identical to the pre-i18n page
 * copy; {@link WebSearchKey} is its key union, and the English dictionary is
 * typed with it, so a missing or extra key on either side is a compile error.
 * The same union constrains the page's `t` seat (`TranslateNS`), so a key
 * removed from the dictionary cannot be rendered.
 *
 * `{name}`-style placeholders are the upstream template syntax. Text the HOST
 * half wrote (engine labels and hints, availability reasons, route errors) is
 * not in here: it crosses the wire already written and is shown verbatim, so
 * this page never re-words it. A few sentences carry inline `<code>` markup in
 * the page — those are split into `…before`/`…after` fragments, because `t`
 * returns a plain string and the term has to stay a real element.
 *
 * @module @dsh-app/plugin-websearch/client/locales
 */

